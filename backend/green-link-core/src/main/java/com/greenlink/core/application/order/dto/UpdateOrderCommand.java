package com.greenlink.core.application.order.dto;

import java.util.List;

public record UpdateOrderCommand(
        Long vendorId,
        Long productId,
        String productName,
        int quantity,
        long amount,
        List<OrderItemCommand> items,
        Long vendorAmount,
        Long extraCost,
        String deliveryDate,
        String deliveryTimeType,
        String deliveryTimeHour,
        String deliveryTimeMinute,
        String deliveryTimeCustom,
        String address,
        String addressDetail,
        String eventType,
        String placeName,
        String roomName,
        String eventInfo,
        String ribbonLeft,
        String ribbonRight,
        String ribbonExtras,
        String ordererName,
        String ordererPhone,
        String recipientName,
        String recipientPhone,
        boolean sendPhotoToOrderer,
        boolean sendPhotoToRecipient,
        String messageSchedule,
        String scheduledMessageHour,
        String scheduledMessageMinute,
        String adminMemo,
        String vendorMemo
) {
    public UpdateOrderCommand withVendorAmount(Long newVendorAmount) {
        return new UpdateOrderCommand(
                vendorId,
                productId,
                productName,
                quantity,
                amount,
                items,
                newVendorAmount,
                extraCost,
                deliveryDate,
                deliveryTimeType,
                deliveryTimeHour,
                deliveryTimeMinute,
                deliveryTimeCustom,
                address,
                addressDetail,
                eventType,
                placeName,
                roomName,
                eventInfo,
                ribbonLeft,
                ribbonRight,
                ribbonExtras,
                ordererName,
                ordererPhone,
                recipientName,
                recipientPhone,
                sendPhotoToOrderer,
                sendPhotoToRecipient,
                messageSchedule,
                scheduledMessageHour,
                scheduledMessageMinute,
                adminMemo,
                vendorMemo);
    }
}
